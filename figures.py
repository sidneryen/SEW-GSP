"""Generate all paper figures (PNG, 300 dpi) from results/*.csv."""
import os, sys
import numpy as np, pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch
from sklearn.decomposition import PCA
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

os.makedirs('figs', exist_ok=True)
plt.rcParams.update({'font.family': 'DejaVu Sans', 'font.size': 9, 'axes.spines.top': False,
                     'axes.spines.right': False, 'axes.grid': True, 'grid.color': '#e6e5e0',
                     'grid.linewidth': 0.6, 'axes.edgecolor': '#52514e', 'axes.labelcolor': '#0b0b0b',
                     'xtick.color': '#52514e', 'ytick.color': '#52514e', 'legend.frameon': False})
STYLE = {  # fixed order, entity-bound colours + marker as secondary encoding
    'SEW-GSP':   dict(color='#2a78d6', marker='o', lw=2.0, ls='-'),
    'HIACSP-WF': dict(color='#eb6834', marker='s', lw=1.6, ls='-'),
    'HIACSP':    dict(color='#1baf7a', marker='^', lw=1.6, ls='-'),
    'HIBOG':     dict(color='#eda100', marker='D', lw=1.6, ls='-'),
    'Raw':       dict(color='#8a8986', marker='x', lw=1.4, ls='--'),
}
ORDER = ['Raw', 'HIBOG', 'HIACSP', 'HIACSP-WF', 'SEW-GSP']


def save(fig, name):
    fig.savefig(f'figs/{name}.png', dpi=300, bbox_inches='tight', facecolor='white')
    os.makedirs('figs/submission', exist_ok=True)               # Springer: vector + high-res copies
    fig.savefig(f'figs/submission/{name}.pdf', bbox_inches='tight', facecolor='white')
    fig.savefig(f'figs/submission/{name}.eps', bbox_inches='tight', facecolor='white')
    fig.savefig(f'figs/submission/{name}.tif', dpi=600, bbox_inches='tight', facecolor='white',
                pil_kwargs={'compression': 'tiff_lzw'})
    plt.close(fig)


